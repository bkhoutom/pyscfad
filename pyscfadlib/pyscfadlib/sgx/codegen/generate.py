"""Generate portable FP64 s--g integral kernels (SymPy is build-time only).

Uses Jesse DiCenso's MIT-licensed SNK generator, vendored in upstream/.
The generated sources are checked in; ordinary builds do not run this file.
Run: python generate.py [--jobs N]
"""
from concurrent.futures import ProcessPoolExecutor
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
import time

ROOT = Path(__file__).resolve().parent.parent
UPSTREAM = Path(__file__).resolve().parent / 'upstream'
sys.path.insert(0, str(UPSTREAM))
LETTERS = 'SPDFG'
ARGS = ('double* out, double* base, const double* boys, const double* p, '
        'const double* gx, const double* gy, const double* gz, '
        'const double* ax, const double* ay, const double* az, '
        'double abx, double aby, double abz, int np, int ng')


def generate(job):
    import codegen
    from recurrences import get_hrr_blist
    la, lb, same, kind = job
    start = time.monotonic()
    output = ROOT / 'generated'
    fn = getattr(codegen, 'generate_' + kind)
    fn(LETTERS[la], LETTERS[lb], same, dname=str(output))
    name = f'{kind.upper()}_{LETTERS[la]}_{LETTERS[lb]}' + ('_SAMECENTER' if same else '')
    notice = ('// Generated by codegen/generate.py; do not edit.\n'
              '// Copyright (c) 2026 Jesse DiCenso. MIT license: ../codegen/upstream/LICENSE\n')
    for suffix in ('.h', '.C'):
        path = output / (name + suffix)
        src = path.read_text()
        if suffix == '.C':
            # Initial backend is FP64. Avoid doubling binary/compiler work.
            src = re.sub(r'template void [^\n]+<float>\([\s\S]*?\);', '', src)
            first, rest = src.split('\n', 1)
            src = first + '\nnamespace pyscfad_sgx {\n' + rest + '\n}\n'
        else:
            src = 'namespace pyscfad_sgx {\n' + src + '\n}\n'
        path.write_text(notice + src)
    nbase = len(get_hrr_blist([la], [lb], same)) if kind == 'hrr' else 0
    row = dict(name=name, la=la, lb=lb, same=same, kind=kind, nbase=nbase,
               source_bytes=(output/(name+'.C')).stat().st_size,
               generation_seconds=time.monotonic()-start)
    print(name, row['source_bytes'], round(row['generation_seconds'], 2), flush=True)
    return row


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--jobs', type=int, default=1)
    args = parser.parse_args()
    output = ROOT / 'generated'
    output.mkdir(exist_ok=True)
    jobs = [(a, b, same, kind) for a in range(5) for b in range(a+1)
            for same in (False, True) for kind in ('vrr', 'hrr')
            if kind == 'vrr' or b > 0]
    with ProcessPoolExecutor(max_workers=args.jobs) as pool:
        rows = list(pool.map(generate, jobs))
    header = ('// Generated by codegen/generate.py.\n#pragma once\n'
              'namespace pyscfad_sgx {\n'
              f'using Kernel = void (*)({ARGS});\n'
              'Kernel select_kernel(int la, int lb, bool same, bool hrr);\n'
              'int base_size(int la, int lb, bool same);\n}\n')
    (output/'kernels.h').write_text(header)
    lines = ['// Generated by codegen/generate.py.', '#include "kernels.h"']
    lines += [f'#include "{r["name"]}.h"' for r in rows]
    lines += ['namespace pyscfad_sgx {']
    for r in rows:
        actual = 'out, ' + ('base, ' if r['kind']=='hrr' else '')
        actual += 'boys, p, gx, gy, gz, '
        if not r['same']:
            actual += 'ax, ay, az, abx, aby, abz, '
        actual += 'np, ng'
        lines += [f'static void wrap_{r["name"]}({ARGS}) {{',
                  f'    {r["name"]}<double>({actual});', '}']
    lines += ['Kernel select_kernel(int la, int lb, bool same, bool hrr) {',
              '    switch (((la*5+lb)*2+same)*2+hrr) {']
    for r in rows:
        key = ((r['la']*5+r['lb'])*2+int(r['same']))*2+int(r['kind']=='hrr')
        lines += [f'    case {key}: return wrap_{r["name"]};']
    lines += ['    default: return nullptr;', '    }', '}',
              'int base_size(int la, int lb, bool same) {',
              '    switch ((la*5+lb)*2+same) {']
    for r in rows:
        if r['kind'] == 'hrr':
            key = (r['la']*5+r['lb'])*2+int(r['same'])
            lines += [f'    case {key}: return {r["nbase"]};']
    lines += ['    default: return 0;', '    }', '}', '}']
    (output/'kernels.cpp').write_text('\n'.join(lines)+'\n')
    manifest = dict(upstream='https://github.com/jesse-dicenso/snk_integral_codegen',
                    upstream_sha256={p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                                     for p in sorted(UPSTREAM.iterdir()) if p.is_file()},
                    kernels=rows)
    (output/'manifest.json').write_text(json.dumps(manifest, indent=2)+'\n')


if __name__ == '__main__':
    main()

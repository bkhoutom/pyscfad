"""Generate FP64 s--g values and first derivatives as shared recurrence DAGs.

No symbolic algebra dependency is needed. Each required (a,b,m) integral is
computed once per primitive/grid point within a bounded group of AO pairs.
Spatial Gaussian derivatives use
    d phi_a / d r_k = a_k phi_(a-e_k) - 2 alpha phi_(a+e_k).
Apply this identity before specializing coincident centers. Raised h shells
are internal intermediates; input shells remain s--g. Output components are
value, three bra spatial derivatives, then three ket spatial derivatives.
"""
from pathlib import Path
import argparse
import hashlib
import json

ROOT = Path(__file__).resolve().parent.parent
ARGS = ('double* out, const double* boys, const double* p, '
        'const double* gx, const double* gy, const double* gz, '
        'const double* ax, const double* ay, const double* az, '
        'double abx, double aby, double abz, '
        'const double* alpha, const double* beta, int npb, int np, int ng')
LETTERS = 'SPDFG'
# Bound the number of output streams seen by one SIMD loop.  Each pair has
# seven read/modify/write outputs; 64 pairs stay below GCC's default 1000
# data-reference analysis limit, without compiler-specific tuning flags.
PAIR_CHUNK = 64


def write_changed(path, text):
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def cartesian(l):
    return [(x, y, l-x-y) for x in range(l, -1, -1)
            for y in range(l-x, -1, -1)]


def shift(a, k, amount):
    result = list(a)
    result[k] += amount
    return tuple(result)


class Recurrences:
    def __init__(self, same):
        self.same = same
        self.nodes = {}
        self.lines = []

    def integral(self, a, b, m=0):
        if min(a+b) < 0:
            return '0.'
        if self.same:
            # At coincident centers the polynomial depends only on a+b.
            # This simplification is applied to the raised/lowered integrals,
            # after the independent-center derivative identity was formed.
            a, b = tuple(x+y for x, y in zip(a, b)), (0, 0, 0)
        if sum(a+b) == 0:
            return f'b{m}'
        key = a, b, m
        if key in self.nodes:
            return self.nodes[key]
        # Match the value VRR's interleaved Cartesian recurrence order.
        k, side = next((k, side) for k in range(3) for side in range(2)
                       if (a, b)[side][k])
        aa, bb = (shift(a, k, -1), b) if side == 0 else (a, shift(b, k, -1))
        terms = []
        axis = 'xyz'[k]
        if not self.same:
            terms.append(f'P{"A" if side == 0 else "B"}{axis} * {self.integral(aa, bb, m)}')
        terms.append(f'- PG{axis} * {self.integral(aa, bb, m+1)}')
        for t, angular in enumerate((aa, bb)):
            if angular[k]:
                aaa, bbb = ((shift(aa, k, -1), bb) if t == 0 else
                            (aa, shift(bb, k, -1)))
                lo = self.integral(aaa, bbb, m)
                hi = self.integral(aaa, bbb, m+1)
                terms.append(f'+ {angular[k]}. * tpi * ({lo} - {hi})')
        name = f'v{len(self.lines)}'
        self.lines.append(f'const double {name} = {" ".join(terms)};')
        self.nodes[key] = name
        return name

    def derivative(self, a, b, side, k):
        angular = (a, b)[side]
        lo_a, lo_b = (shift(a, k, -1), b) if side == 0 else (a, shift(b, k, -1))
        hi_a, hi_b = (shift(a, k, 1), b) if side == 0 else (a, shift(b, k, 1))
        raised = self.integral(hi_a, hi_b)
        term = f'- {"two_alpha" if side == 0 else "two_beta"} * {raised}'
        if angular[k]:
            term = f'{angular[k]}. * {self.integral(lo_a, lo_b)} ' + term
        return term


def generate(la, lb, same, output):
    pairs = [(a, b) for a in cartesian(la) for b in cartesian(lb)]
    name = f'VD_{LETTERS[la]}_{LETTERS[lb]}' + ('_SAMECENTER' if same else '')
    lines = ['// Generated by codegen/generate_derivatives.py; do not edit.',
             '// Copyright 2026 The PySCFAD Authors. Apache License, Version 2.0.',
             '#include "derivatives.h"', 'namespace pyscfad_sgx {',
             f'void {name}({ARGS}) {{',
             f'    for (int i=0; i<{7*len(pairs)}*ng; ++i) out[i]=0.;',
             '    for (int prim=0; prim<np; ++prim) {',
             '        const double two_alpha=2*alpha[prim/npb];',
             '        const double two_beta=2*beta[prim%npb];']
    if la+lb:
        lines += ['        const double tpi=.5/p[prim];']
    if not same:
        for axis in 'xyz':
            lines += [f'        const double PA{axis}=a{axis}[prim];',
                      f'        const double PB{axis}=PA{axis}+ab{axis};']
    nodes = []
    for start in range(0, len(pairs), PAIR_CHUNK):
        chunk = pairs[start:start+PAIR_CHUNK]
        dag = Recurrences(same)
        expressions = [dag.integral(a, b) for a, b in chunk]
        expressions += [dag.derivative(a, b, side, k) for side in range(2)
                        for k in range(3) for a, b in chunk]
        # Each bounded loop still shares the value and all six derivatives.
        # Boys values and primitive geometry are shared across every chunk.
        lines += ['        #pragma omp simd', '        for (int g=0; g<ng; ++g) {']
        for axis in 'xyz':
            lines += [f'            const double PG{axis}=g{axis}[prim*ng+g];']
        for m in range(la+lb+2):
            lines += [f'            const double b{m}=boys[(prim*{la+lb+2}+{m})*ng+g];']
        lines += ['            '+line for line in dag.lines]
        for i, expr in enumerate(expressions):
            component, pair = divmod(i, len(chunk))
            offset = component*len(pairs)+start+pair
            lines += [f'            out[{offset}*ng+g] += {expr};']
        lines += ['        }']
        nodes.append(len(dag.lines))
    lines += ['    }', '}', '}']
    path = output/(name+'.C')
    write_changed(path, '\n'.join(lines)+'\n')
    row = dict(name=name, la=la, lb=lb, same=same,
               recurrence_nodes=sum(nodes), simd_chunks=len(nodes),
               max_pairs_per_loop=PAIR_CHUNK, source_bytes=path.stat().st_size)
    print(name, row['recurrence_nodes'], row['source_bytes'], flush=True)
    return row


def generate_all():
    output = ROOT/'generated'
    output.mkdir(exist_ok=True)
    rows = [generate(a, b, same, output) for a in range(5)
            for b in range(a+1) for same in (False, True)]
    header = ['// Generated by codegen/generate_derivatives.py.', '#pragma once',
              'namespace pyscfad_sgx {', f'using DerivativeKernel = void (*)({ARGS});',
              'DerivativeKernel select_derivative_kernel(int la, int lb, bool same);']
    header += [f'void {row["name"]}({ARGS});' for row in rows]
    header += ['}']
    write_changed(output/'derivatives.h', '\n'.join(header)+'\n')
    dispatch = ['// Generated by codegen/generate_derivatives.py.',
                '#include "derivatives.h"', 'namespace pyscfad_sgx {',
                'DerivativeKernel select_derivative_kernel(int la, int lb, bool same) {',
                '    switch ((la*5+lb)*2+same) {']
    dispatch += [f'    case {(r["la"]*5+r["lb"])*2+int(r["same"])}: return {r["name"]};'
                 for r in rows]
    dispatch += ['    default: return nullptr;', '    }', '}', '}']
    write_changed(output/'derivatives.cpp', '\n'.join(dispatch)+'\n')
    manifest = dict(generator='codegen/generate_derivatives.py',
                    generator_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                    components=['value', 'ip1_x', 'ip1_y', 'ip1_z', 'ip2_x', 'ip2_y', 'ip2_z'],
                    kernels=rows)
    write_changed(output/'derivatives_manifest.json', json.dumps(manifest, indent=2)+'\n')


if __name__ == '__main__':
    argparse.ArgumentParser(description=__doc__).parse_args()
    generate_all()

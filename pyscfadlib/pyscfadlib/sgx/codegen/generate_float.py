"""Generate FP32 siblings of the checked-in FP64 value/derivative kernels.

Run after generate.py and generate_derivatives.py. No symbolic algebra is
needed: recurrence graphs and chunk boundaries are shared by both precisions.
The separate namespace keeps the original FP64 reference kernels unchanged.
"""
from pathlib import Path
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parent.parent / 'generated'


def main():
    target = ROOT / 'fp32'
    target.mkdir(exist_ok=True)
    rows = []
    for path in sorted(ROOT.iterdir()):
        if path.suffix not in ('.C', '.cpp', '.h'):
            continue
        # Contracted derivative HRR remains FP64: FP32 translation can amplify
        # roundoff beyond the component-wise accuracy budget.
        if path.name.startswith('HD_') or path.stem == 'hrr_derivatives':
            continue
        text = path.read_text().replace('double', 'float')
        # Avoid silently promoting recurrence arithmetic to double precision.
        text = re.sub(r'(?<![\w.])(\d+\.\d*|\.\d+)([eE][+-]?\d+)?(?![\w.])',
                      lambda m: m.group(0)+'f', text)
        text = text.replace('namespace pyscfad_sgx {',
                            'namespace pyscfad_sgx { namespace fp32 {')
        text += '\n} // namespace pyscfad_sgx\n'
        text = '// Generated by codegen/generate_float.py from ../'+path.name+'\n'+text
        output = target / path.name
        if not output.exists() or output.read_text() != text:
            output.write_text(text)
        rows.append(dict(file=path.name, source_sha256=hashlib.sha256(path.read_bytes()).hexdigest()))
    (target/'manifest.json').write_text(json.dumps(dict(sources=rows), indent=2)+'\n')


if __name__ == '__main__':
    main()

"""Generate contracted HRR derivatives; ordinary/2alpha/2beta bases.

The exponent weights are contracted before HRR. Applying exponent factors
AFTER primitive contraction would be incorrect for general contractions.
Uses the existing portable VRR DAG generator for (L,0) primitive bases.
"""
from pathlib import Path
import importlib.util,json
ROOT=Path(__file__).resolve().parent.parent
spec=importlib.util.spec_from_file_location('vrr_generator',ROOT/'codegen/generate_derivatives.py')
vrr=importlib.util.module_from_spec(spec);spec.loader.exec_module(vrr)
ARGS=vrr.ARGS.replace('double* out,','double* out, double* base,')
ZERO=(0,0,0)

class HRR:
    def __init__(self,same,leaves):
        self.same,self.leaves=same,leaves
        self.nodes={};self.lines=[]
    def integral(self,a,b,family=0):
        if min(a+b)<0:return '0.'
        if self.same:a,b=tuple(x+y for x,y in zip(a,b)),ZERO
        if b==ZERO:
            key=(family,a)
            if key not in self.leaves:self.leaves[key]=len(self.leaves)
            return f'base[{self.leaves[key]}*ng+g]'
        key=(family,a,b)
        if key not in self.nodes:
            k=next(k for k in range(3) if b[k])
            lower=vrr.shift(b,k,-1)
            raised=self.integral(vrr.shift(a,k,1),lower,family)
            other=self.integral(a,lower,family)
            name=f'h{len(self.lines)}'
            self.lines.append(f'const double {name} = {raised} + ab{"xyz"[k]} * {other};')
            self.nodes[key]=name
        return self.nodes[key]
    def derivative(self,a,b,side,k):
        angular=(a,b)[side]
        aa,bb=(vrr.shift(a,k,1),b) if side==0 else (a,vrr.shift(b,k,1))
        expr='- '+self.integral(aa,bb,side+1)
        if angular[k]:
            aa,bb=(vrr.shift(a,k,-1),b) if side==0 else (a,vrr.shift(b,k,-1))
            expr=f'{angular[k]}. * {self.integral(aa,bb)} '+expr
        return expr

def generate(la,lb,same):
    name=f'HD_{vrr.LETTERS[la]}_{vrr.LETTERS[lb]}'+('_SAMECENTER' if same else '')
    pairs=[(a,b) for a in vrr.cartesian(la) for b in vrr.cartesian(lb)]
    leaves={};groups=[]
    for start in range(0,len(pairs),64):
        chunk=pairs[start:start+64];dag=HRR(same,leaves)
        expr=[dag.integral(a,b) for a,b in chunk]
        expr += [dag.derivative(a,b,side,k) for side in (0,1) for k in range(3) for a,b in chunk]
        groups.append((start,len(chunk),dag.lines,expr))
    lines=['// Generated by codegen/generate_hrr_derivatives.py; do not edit.', '#include "hrr_derivatives.h"','namespace pyscfad_sgx {',f'void {name}({ARGS}) {{',f'    for(int i=0;i<{len(leaves)}*ng;++i)base[i]=0.;',
        '    for(int prim=0;prim<np;++prim) {','        const double two_alpha=2*alpha[prim/npb],two_beta=2*beta[prim%npb];','        const double tpi=.5/p[prim];']
    if not same:
        lines += [f'        const double PA{k}=a{k}[prim];' for k in 'xyz']
    angulars=list(dict.fromkeys(a for family,a in leaves))
    for first in range(0,len(angulars),48):
        group=angulars[first:first+48];dag=vrr.Recurrences(same)
        vals={a:dag.integral(a,ZERO) for a in group}
        lines += ['        #pragma omp simd','        for(int g=0;g<ng;++g) {']
        lines += [f'            const double PG{k}=g{k}[prim*ng+g];' for k in 'xyz']
        lines += [f'            const double b{m}=boys[(prim*{la+lb+2}+{m})*ng+g];' for m in range(la+lb+2)]
        lines += ['            '+x for x in dag.lines]
        for a,value in vals.items():
            for family,factor in enumerate(('', 'two_alpha * ', 'two_beta * ')):
                if (family,a) in leaves:lines += [f'            base[{leaves[family,a]}*ng+g] += {factor}{value};']
        lines += ['        }']
    lines += ['    }']
    for start,size,nodes,expr in groups:
        lines += ['    #pragma omp simd','    for(int g=0;g<ng;++g) {']
        lines += ['        '+x for x in nodes]
        for i,value in enumerate(expr):
            comp,pair=divmod(i,size)
            lines += [f'        out[{comp*len(pairs)+start+pair}*ng+g] = {value};']
        lines += ['    }']
    lines += ['}','}']
    vrr.write_changed(ROOT/'generated'/f'{name}.C', '\n'.join(lines)+'\n')
    return dict(name=name,la=la,lb=lb,same=same,base_size=len(leaves))
def main():
    rows=[generate(a,b,same) for a in range(5) for b in range(a+1) for same in (False,True)]
    header=['#pragma once','namespace pyscfad_sgx {',f'using HRRDerivativeKernel = void (*)({ARGS});','HRRDerivativeKernel select_hrr_derivative(int,int,bool);','int hrr_derivative_base_size(int,int,bool);']
    header += [f'void {r["name"]}({ARGS});' for r in rows]
    header += ['}']
    vrr.write_changed(ROOT/'generated/hrr_derivatives.h', '\n'.join(header)+'\n')
    lines=['#include "hrr_derivatives.h"','namespace pyscfad_sgx {','HRRDerivativeKernel select_hrr_derivative(int a,int b,bool same) {','switch((a*5+b)*2+same) {']
    lines += [f'case {(r["la"]*5+r["lb"])*2+int(r["same"])}: return {r["name"]};' for r in rows]
    lines += ['default:return nullptr;}}','int hrr_derivative_base_size(int a,int b,bool same) {','switch((a*5+b)*2+same) {']
    lines += [f'case {(r["la"]*5+r["lb"])*2+int(r["same"])}: return {r["base_size"]};' for r in rows]
    lines += ['default:return 0;}}','}']
    vrr.write_changed(ROOT/'generated/hrr_derivatives.cpp', '\n'.join(lines)+'\n')
    (ROOT/'generated/derivative_hrr_manifest.json').write_text(json.dumps(rows,indent=2)+'\n')
    print('Generated',len(rows),'HRR derivative kernels; largest base',max(r['base_size'] for r in rows))


if __name__ == "__main__":
    main()
